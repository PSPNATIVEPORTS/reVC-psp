# Generates src/skel/3ds/n3dsbuttons.h: 3DS button icons (32x32 RGBA) that
# replace the PlayStation ones in the game's help texts.
# Order = eButtonIcons in renderer/Font.h. The PSP port's mapping:
# Cross=B, Circle=A, Square=Y, Triangle=X, L1=L, R1=R, L2/R2 = d-pad left/right,
# L3 = d-pad down, R3 = d-pad up, sticks = circle pad.
from PIL import Image, ImageDraw, ImageFont
import sys
S = 32; SS = 4  # draw 4x, downscale (antialiasing)
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'

def canvas():
    im = Image.new('RGBA', (S*SS, S*SS), (0, 0, 0, 0))
    return im, ImageDraw.Draw(im)

def text(d, t, size, cx, cy, fill=(255, 255, 255, 255)):
    f = ImageFont.truetype(FONT, size*SS)
    b = d.textbbox((0, 0), t, font=f)
    d.text((cx*SS - (b[0]+b[2])/2, cy*SS - (b[1]+b[3])/2), t, font=f, fill=fill)

def face(letter):
    im, d = canvas()
    d.ellipse((1*SS, 1*SS, 31*SS, 31*SS), fill=(25, 25, 28, 255), outline=(200, 200, 205, 255), width=2*SS)
    text(d, letter, 18, 16, 16.5)
    return im

def shoulder(letter):
    im, d = canvas()
    d.rounded_rectangle((1*SS, 7*SS, 31*SS, 25*SS), radius=8*SS, fill=(25, 25, 28, 255), outline=(200, 200, 205, 255), width=2*SS)
    text(d, letter, 15, 16, 16)
    return im

def dpad(hl):
    im, d = canvas()
    g = (90, 90, 95, 255); w = (255, 255, 255, 255); o = (20, 20, 22, 255)
    arms = {'up': (11, 1, 21, 13), 'down': (11, 19, 21, 31), 'left': (1, 11, 13, 21), 'right': (19, 11, 31, 21)}
    d.rectangle((10*SS, 0, 22*SS, 32*SS), fill=o); d.rectangle((0, 10*SS, 32*SS, 22*SS), fill=o)
    for k, r in arms.items():
        d.rectangle(tuple(v*SS for v in r), fill=w if k == hl else g)
    d.rectangle((11*SS, 11*SS, 21*SS, 21*SS), fill=g)
    return im

def cpad(direction):
    im, d = canvas()
    d.ellipse((1*SS, 1*SS, 31*SS, 31*SS), fill=(60, 60, 65, 255), outline=(200, 200, 205, 255), width=2*SS)
    d.ellipse((8*SS, 8*SS, 24*SS, 24*SS), fill=(110, 110, 115, 255))
    tri = {'up': [(16, 2), (11, 8), (21, 8)], 'down': [(16, 30), (11, 24), (21, 24)],
           'left': [(2, 16), (8, 11), (8, 21)], 'right': [(30, 16), (24, 11), (24, 21)]}[direction]
    d.polygon([(x*SS, y*SS) for x, y in tri], fill=(255, 255, 255, 255))
    return im

icons = [cpad('up'), cpad('down'), cpad('left'), cpad('right'),
         face('B'), face('A'), face('Y'), face('X'),
         shoulder('L'), dpad('left'), dpad('down'),
         shoulder('R'), dpad('right'), dpad('up'),
         cpad('up'), cpad('down'), cpad('left'), cpad('right')]
out = open(sys.argv[1], 'w')
out.write('// generated by utils/3dsicons/make_icons.py: 3DS button icons, %d x 32x32 RGBA\n' % len(icons))
out.write('static const unsigned char n3dsButtonIcons[%d][32*32*4] = {\n' % len(icons))
for im in icons:
    im = im.resize((S, S), Image.LANCZOS)
    out.write('{' + ','.join(str(b) for b in im.tobytes()) + '},\n')
out.write('};\n')
sheet = Image.new('RGBA', (S*len(icons), S), (40, 120, 60, 255))
for i, im in enumerate(icons):
    sheet.alpha_composite(im.resize((S, S), Image.LANCZOS), (i*S, 0))
sheet.save('/tmp/icons_sheet.png')
